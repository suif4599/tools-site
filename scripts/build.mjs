#!/usr/bin/env node
// Derives site artifacts from tools.toml: public/_headers, src/routes.gen.ts and the index.html tool cards.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse } from 'smol-toml';

function vendor(from, to) {
  mkdirSync(to.slice(0, to.lastIndexOf('/')), { recursive: true });
  copyFileSync(from, to);
}

vendor('node_modules/@yunyoujun/ak-ui/dist/tokens.css', 'public/ui/ak-tokens.css');
vendor('node_modules/@yunyoujun/ak-ui/dist/ak-ui.css', 'public/ui/ak-ui.css');
vendor('node_modules/@yunyoujun/ak-ui/src/js/effects.mjs', 'public/ui/ak-effects.mjs');
for (const weight of [500, 600]) {
  vendor(`node_modules/@fontsource/oswald/files/oswald-latin-${weight}-normal.woff2`, `public/ui/fonts/oswald-latin-${weight}-normal.woff2`);
}

const BASE_CSP = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' https://static.cloudflareinsights.com",
  "style-src 'self'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self' https://cloudflareinsights.com",
  "object-src 'none'",
  "base-uri 'self'",
  "frame-src 'self'",
].join('; ') + ';';

const LOGIN_CSP = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' https://challenges.cloudflare.com https://static.cloudflareinsights.com",
  "style-src 'self'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self' https://challenges.cloudflare.com https://cloudflareinsights.com",
  "object-src 'none'",
  "base-uri 'self'",
  "frame-src 'self' https://challenges.cloudflare.com",
].join('; ') + ';';

const tools = parse(readFileSync('tools.toml', 'utf8')).tool;
for (const t of tools) {
  if (!/^[a-z0-9-]+$/.test(t.id)) throw new Error(`tool id must be [a-z0-9-]+: ${t.id}`);
  if (!/^\/.*\/$/.test(t.route)) throw new Error(`tool route must start and end with "/": ${t.id}`);
  const artifact = join('public', ...t.route.split('/').filter(Boolean), 'index.html');
  if (!existsSync(artifact)) {
    throw new Error(`missing tool artifact ${artifact}; run: node scripts/sync.mjs ${t.id}`);
  }
}

const headers = [
  '/',
  '  Cache-Control: no-cache',
  `  Content-Security-Policy: ${BASE_CSP}`,
  '/index.html',
  '  Cache-Control: no-cache',
  `  Content-Security-Policy: ${BASE_CSP}`,
  '/about',
  '  Cache-Control: no-cache',
  `  Content-Security-Policy: ${BASE_CSP}`,
  '/about.html',
  '  Cache-Control: no-cache',
  `  Content-Security-Policy: ${BASE_CSP}`,
  '/login',
  '  Cache-Control: no-cache',
  `  Content-Security-Policy: ${LOGIN_CSP}`,
  '/ui/*',
  '  Cache-Control: public, max-age=3600',
];
for (const t of tools) {
  if (t['needs-isolation']) {
    headers.push(
      `${t.route}*`,
      '  Cross-Origin-Opener-Policy: same-origin',
      '  Cross-Origin-Embedder-Policy: require-corp',
      '  Cross-Origin-Resource-Policy: same-origin',
    );
  }
}
writeFileSync('public/_headers', headers.join('\n') + '\n');

const gen = `// Generated by scripts/build.mjs from tools.toml — do not edit by hand.
export interface ToolRoute {
  id: string;
  route: string;
  title: string;
  public: boolean;
  requiresRole: string | null;
  isolation: boolean;
  r2Prefix: string | null;
  wasm: boolean;
  inlineStyle: boolean;
  storage: boolean;
}
export const TOOLS: ToolRoute[] = [
${tools.map((t) => `  { id: ${JSON.stringify(t.id)}, route: ${JSON.stringify(t.route)}, title: ${JSON.stringify(t.title)}, public: ${!!t.public}, requiresRole: ${t['requires-role'] ? JSON.stringify(t['requires-role']) : 'null'}, isolation: ${!!t['needs-isolation']}, r2Prefix: ${t['r2-prefix'] ? JSON.stringify(t['r2-prefix']) : 'null'}, wasm: ${!!t['needs-wasm']}, inlineStyle: ${!!t['needs-inline-style']}, storage: ${!!t.storage} },`).join('\n')}
];
`;
writeFileSync('src/routes.gen.ts', gen);

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const cards = tools
  .filter((t) => !t['requires-role'])
  .map((t, i) => `  <a class="card ak-command" href="${esc(t.route)}"><span class="ak-command__badge">${String(i + 1).padStart(2, '0')}</span><span class="ak-command__watermark" aria-hidden="true">${esc(t.id)}</span><h2 class="ak-command__label">${esc(t.title)}</h2><p class="ak-command__meta">${esc(t.description || '')}</p></a>`)
  .join('\n');
const index = readFileSync('public/index.html', 'utf8');
writeFileSync(
  'public/index.html',
  index.replace(/<!-- TOOLS:START -->[\s\S]*?<!-- TOOLS:END -->/, `<!-- TOOLS:START -->\n${cards}\n  <!-- TOOLS:END -->`),
);

console.log(`build: ${tools.length} tools -> public/_headers, src/routes.gen.ts, index.html cards`);
